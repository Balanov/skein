#!/usr/bin/env python3
"""Generate compact landing data and publish exact raw evidence into site/dist."""
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "bench" / "results"
PUBLIC = ROOT / "site" / "public" / "results"
FILES = {
    "independent": "windows-amd64-scheduler-independent.json",
    "chain": "windows-amd64-scheduler-chain.json",
    "fanout": "windows-amd64-scheduler-fanout.json",
    "process": "windows-amd64-process-workload.json",
    "stop": "windows-amd64-stop.json",
    "functional": "windows-amd64-functional.json",
    "tests": "windows-amd64-tests.jsonl",
}


def read_json(name):
    return json.loads((RESULTS / name).read_text(encoding="utf-8"))


def main():
    documents = {key: read_json(name) for key, name in FILES.items() if name.endswith(".json")}
    scheduler = {}
    for shape in ("independent", "chain", "fanout"):
        document = documents[shape]
        scheduler[shape] = {
            "method": document["method"],
            "scope": document["scope"],
            "skipped": document["skipped"],
            "results": [{
                "tasks": result["tasks"],
                "candidate": result["raw"]["candidate"],
                "candidate_version": result["raw"].get("candidate_version") or result["raw"].get("go_version"),
                "inner_repetitions": result["raw"].get("inner_repetitions", 1),
                **result["summary"],
            } for result in document["results"] if result["raw"]["candidate"] != "go-goroutines"],
        }
    process = documents["process"]
    stop = documents["stop"]
    functional = documents["functional"]
    test_events = [json.loads(line) for line in (RESULTS / FILES["tests"]).read_text(encoding="utf-8").splitlines()]
    passed = sorted({(event["Package"], event["Test"]) for event in test_events if event.get("Action") == "pass" and event.get("Test")})
    test_logs = [event.get("Output", "").strip() for event in test_events if "verified " in event.get("Output", "")]

    functional_scenarios = []
    for scenario in functional["scenarios"]:
        keep = ["name", "passed", "expected_output", "observed_output", "statuses", "expected_exit_code", "observed_exit_code", "diagnostic", "events"]
        functional_scenarios.append({key: value for key, value in scenario.items() if key in keep})

    evidence = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "machine": documents["independent"]["machine"],
        "scheduler": scheduler,
        "process": {
            "scope": process["scope"],
            "method": process["method"],
            "tasks_per_run": process["tasks_per_run"],
            "workers": process["workers"],
            "payload_bytes": process["payload_bytes"],
            "expected_sha256": process["expected_sha256"],
            "results": process["results"],
        },
        "stop": {
            "scope": stop["scope"],
            "method": stop["method"],
            "summary": stop["summary"],
            "processes_per_run": stop["processes_per_run"],
        },
        "functional": {"summary": functional["summary"], "scenarios": functional_scenarios},
        "tests": {
            "passed_tests_and_subtests": len(passed),
            "top_level": sum("/" not in test for _, test in passed),
            "packages": len({package for package, _ in passed}),
            "logs": test_logs,
        },
        "raw_files": FILES,
    }
    PUBLIC.mkdir(parents=True, exist_ok=True)
    for name in FILES.values():
        shutil.copyfile(RESULTS / name, PUBLIC / name)
    output = ROOT / "site" / "src" / "results.js"
    output.write_text("// Generated by bench/render_results.py from bench/results; do not edit.\nexport const evidence = " + json.dumps(evidence, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote {output} and {len(FILES)} raw evidence files")


if __name__ == "__main__":
    main()
